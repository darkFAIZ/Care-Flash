import 'dart:convert';
import 'dart:math';

import '../platform_policy.dart';

/// Why a scanned safety-button payload was rejected.
///
/// A failed check cancels the booking, records the failure and notifies support.
/// There is no retry. (FR-CS-15, FR-CM-14, FR-P-18)
enum ButtonCodeFailure {
  noCode('No safety button has been activated for this booking.'),

  wrongBooking('That safety button belongs to a different booking.'),

  wrongNonce('That safety button does not match this booking.'),

  expired('That safety button code has expired.'),

  alreadyUsed('That safety button code has already been used.');

  const ButtonCodeFailure(this.label);

  final String label;
}

/// Booking-linked safety-button code. (FR-P-17, FR-P-18, HI-1)
///
/// Two different codes exist and they must never be mixed up:
///
///  * The *client verification code* is generated by the platform after
///    payment. Only the care seeker sees it and the caregiver types it in.
///  * The *safety-button code* below is generated by the caregiver app after
///    the client code is valid. The CARE SEEKER verifies it by scanning the QR
///    code or reading the NFC tag; the caregiver can never confirm it.
///
/// The payload is `careflash://button/{bookingId}/{nonce}` plus a mock
/// signature. It is single use, tied to one booking and expires after
/// [PlatformPolicy.safetyButtonCodeTtl].
class ButtonCode {
  const ButtonCode({
    required this.bookingId,
    required this.nonce,
    required this.signature,
    required this.issuedAt,
    required this.expiresAt,
    this.usedAt,
  });

  /// URI scheme used by the QR and NFC payloads.
  static const String scheme = 'careflash://button';

  final String bookingId;

  /// Random value that ties the code to one booking and one hand-over attempt.
  final String nonce;

  /// Mock signature over [bookingId] and [nonce].
  /// TODO(team): replace with a real signing scheme before launch. (FR-P-17)
  final String signature;

  final DateTime issuedAt;
  final DateTime expiresAt;

  /// Set once the care seeker's scan has been accepted, which makes the code
  /// single use.
  final DateTime? usedAt;

  /// True once the care seeker's scan has consumed this code.
  bool get isUsed => usedAt != null;

  /// True from [expiresAt] onwards. The code is valid for
  /// [PlatformPolicy.safetyButtonCodeTtl] and stops being accepted at that
  /// exact moment.
  bool isExpiredAt(DateTime now) => !now.isBefore(expiresAt);

  /// The QR/NFC payload shown by the caregiver and read by the care seeker.
  String get payload => '$scheme/$bookingId/$nonce';

  /// Returns a copy stamped as used at [at].
  ButtonCode markUsed(DateTime at) => ButtonCode(
        bookingId: bookingId,
        nonce: nonce,
        signature: signature,
        issuedAt: issuedAt,
        expiresAt: expiresAt,
        usedAt: at,
      );

  /// Checks a scanned [payload] for [bookingId] at [now].
  ///
  /// Returns `null` when the payload belongs to this booking, matches the
  /// nonce, has not expired and has not been used before. Anything else is a
  /// failure that must cancel the booking.
  ButtonCodeFailure? validate(String bookingId, String payload, DateTime now) {
    final parsed = parsePayload(payload);
    if (parsed == null) {
      return ButtonCodeFailure.wrongNonce;
    }
    if (parsed.bookingId != this.bookingId || parsed.bookingId != bookingId) {
      return ButtonCodeFailure.wrongBooking;
    }
    if (parsed.nonce != nonce) {
      return ButtonCodeFailure.wrongNonce;
    }
    if (isUsed) {
      return ButtonCodeFailure.alreadyUsed;
    }
    if (isExpiredAt(now)) {
      return ButtonCodeFailure.expired;
    }
    return null;
  }

  /// Splits a `careflash://button/{bookingId}/{nonce}` payload, or returns
  /// `null` when it is malformed.
  static ({String bookingId, String nonce})? parsePayload(String payload) {
    final trimmed = payload.trim();
    if (!trimmed.startsWith('$scheme/')) {
      return null;
    }
    final parts = trimmed.substring(scheme.length + 1).split('/');
    if (parts.length != 2 || parts.any((part) => part.isEmpty)) {
      return null;
    }
    return (bookingId: parts[0], nonce: parts[1]);
  }

  /// Mock signature. Deterministic for a given booking and nonce so a check
  /// can compare it.
  static String mockSignature(String bookingId, String nonce) =>
      base64Url.encode(utf8.encode('$bookingId|$nonce|careflash'));

  /// Mints a fresh code for [bookingId], valid from [now] for [ttl].
  ///
  /// [random] is injectable so tests can build a deterministic nonce.
  static ButtonCode generate({
    required String bookingId,
    DateTime? now,
    Duration ttl = PlatformPolicy.safetyButtonCodeTtl,
    Random? random,
  }) {
    final issuedAt = now ?? DateTime.now();
    final rng = random ?? Random.secure();
    final nonce = _randomNonce(rng);
    return ButtonCode(
      bookingId: bookingId,
      nonce: nonce,
      signature: mockSignature(bookingId, nonce),
      issuedAt: issuedAt,
      expiresAt: issuedAt.add(ttl),
    );
  }

  static String _randomNonce(Random rng) {
    const chars = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
    final buffer = StringBuffer();
    for (var i = 0; i < 12; i++) {
      buffer.write(chars[rng.nextInt(chars.length)]);
    }
    return buffer.toString();
  }

  Map<String, Object?> toJson() => {
        'bookingId': bookingId,
        'nonce': nonce,
        'signature': signature,
        'issuedAt': issuedAt.toIso8601String(),
        'expiresAt': expiresAt.toIso8601String(),
        'usedAt': usedAt?.toIso8601String(),
      };

  factory ButtonCode.fromJson(Map<String, Object?> json) => ButtonCode(
        bookingId: json['bookingId']! as String,
        nonce: json['nonce']! as String,
        signature: json['signature']! as String,
        issuedAt: DateTime.parse(json['issuedAt']! as String),
        expiresAt: DateTime.parse(json['expiresAt']! as String),
        usedAt: json['usedAt'] == null
            ? null
            : DateTime.parse(json['usedAt']! as String),
      );
}
